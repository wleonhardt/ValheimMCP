#!/usr/bin/env python3
"""Tool catalogue lint. Collects every registered tool from the C# sources (r.Add("name", ...), Reg.Add(r, "name", ...), and the core's built-in AppendTool(sb, "name", ...)),
checks the names (unique, snake_case) and that each has a real description, and keeps docs/TOOLS.md -- the generated catalogue -- in step with the code.

  python3 scripts/lint_tools.py            check (CI)
  python3 scripts/lint_tools.py --write    regenerate docs/TOOLS.md
"""
import os, re, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from csscan import mask, line_of

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, 'docs', 'TOOLS.md')
NAME = re.compile(r'^[a-z][a-z0-9]*(_[a-z0-9]+)*$')
BUILTIN_WRITE = {'run_command'}      # core tools that need tools.write
CALL = re.compile(r'(?:\br\.Add\(|\bReg\.Add\(r,\s*|\bAppendTool\(sb,\s*)"([A-Za-z0-9_]+)"')

def string_literals(src, start):
    """The adjacent string literals ("a" + "b" + ...) that begin at start (the first one after the name's comma), unescaped and joined."""
    i = start; parts = []
    n = len(src)
    while i < n:
        while i < n and src[i] in ' \t\r\n+': i += 1
        if i < n and src[i] == '"':
            j = i + 1; buf = []
            while j < n and src[j] != '"':
                if src[j] == '\\' and j + 1 < n:
                    esc = src[j + 1]; buf.append({'n': '\n', 't': '\t', '"': '"', '\\': '\\', "'": "'"}.get(esc, esc)); j += 2
                else:
                    buf.append(src[j]); j += 1
            parts.append(''.join(buf)); i = j + 1
        else:
            break
    return ''.join(parts)

def statement_end(masked, start):
    d = 0
    for k in range(start, len(masked)):
        c = masked[k]
        if c == '(': d += 1
        elif c == ')':
            if d == 0: return k
            d -= 1
    return len(masked)

def collect():
    files = subprocess.check_output(['git', 'ls-files', '--cached', '--others', '--exclude-standard', 'src/*.cs', 'ext/*.cs'], cwd=ROOT, text=True).split()
    cats = {}
    reg = os.path.join(ROOT, 'ext', 'Reg.cs')
    if os.path.exists(reg):
        for m in re.finditer(r'foreach \(var n in "([^"]+)"\.Split\(\' \'\)\) Category\[n\] = "(\w+)"', open(reg, encoding='utf-8').read()):
            for n in m.group(1).split(): cats[n] = m.group(2)
    tools = []
    for f in files:
        if not f.endswith('.cs'): continue
        text = open(os.path.join(ROOT, f), encoding='utf-8').read()
        m = mask(text)
        for mt in CALL.finditer(text):
            if m[mt.start():mt.start() + 1].isspace() and False: continue
            name = mt.group(1)
            # skip matches that sit in a comment
            if m[mt.start():mt.end()].strip().startswith(' ') and not m[mt.start():mt.end()].strip(): continue
            after = mt.end()
            comma = text.find(',', after)
            desc = string_literals(text, comma + 1) if comma >= 0 else ''
            end = statement_end(m, mt.start() + len(mt.group(0)) - len(name) - 2)
            stmt = text[mt.start():end + 1].rstrip()
            tail = re.sub(r'\s+', ' ', stmt[-60:])
            write = bool(re.search(r',\s*(true|W|Plans\.WriteFlag)\)\s*$', stmt)) or ', true)' in tail
            write = write or name in BUILTIN_WRITE
            tools.append({'name': name, 'file': f, 'line': line_of(text, mt.start()), 'desc': desc, 'write': write, 'cat': cats.get(name, 'built-in' if f.endswith('McpServer.cs') else 'misc')})
    return tools

def first_sentence(d):
    d = re.sub(r'\s+', ' ', d).strip()
    i = -1
    for m in re.finditer(r'\. ', d):
        before = d[max(0, m.start() - 4):m.start()]
        if m.start() > 20 and not re.search(r'(e\.g|i\.e|etc|vs)$', before):
            i = m.start(); break
    return (d[:i + 1] if i > 0 else d).replace('|', '\\|')

def render(tools):
    seen = {}
    for t in tools: seen.setdefault(t['name'], t)
    rows = sorted(seen.values(), key=lambda t: t['name'])
    out = ['# Tool catalogue', '', 'Generated by `python3 scripts/lint_tools.py --write` from the C# sources; CI fails when it is out of date. Edit the tool descriptions in the code, not this file.', '',
           '| Tool | Where | Category | Write | What |', '|---|---|---|---|---|']
    for t in rows:
        out.append(f"| `{t['name']}` | {t['file']} | {t['cat']} | {'yes' if t['write'] else ''} | {first_sentence(t['desc'])} |")
    out.append('')
    out.append(f'{len(rows)} tools.')
    return '\n'.join(out) + '\n'

def problems(tools):
    errs = []
    first = {}
    for t in tools:
        if not NAME.match(t['name']): errs.append(f"{t['file']}:{t['line']}: tool name '{t['name']}' is not snake_case")
        if len(t['desc'].strip()) < 20: errs.append(f"{t['file']}:{t['line']}: tool '{t['name']}' has no real description")
        if t['name'] in first and first[t['name']]['file'] != t['file'] and not (first[t['name']]['file'].endswith('McpServer.cs') or t['file'].endswith('McpServer.cs')):
            errs.append(f"{t['file']}:{t['line']}: tool '{t['name']}' is also registered in {first[t['name']]['file']}:{first[t['name']]['line']}")
        first.setdefault(t['name'], t)
    return errs

def main(argv):
    tools = collect()
    errs = problems(tools)
    if errs:
        print('\n'.join(errs)); return 1
    text = render(tools)
    if '--write' in argv:
        os.makedirs(os.path.dirname(DOC), exist_ok=True); open(DOC, 'w', encoding='utf-8').write(text); print(f'wrote docs/TOOLS.md ({text.count(chr(10))} lines)'); return 0
    cur = open(DOC, encoding='utf-8').read() if os.path.exists(DOC) else ''
    if cur != text:
        print('docs/TOOLS.md is out of date: run python3 scripts/lint_tools.py --write and commit it'); return 1
    print('ok: ' + text.strip().splitlines()[-1]); return 0

if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
